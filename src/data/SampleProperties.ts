export const getSimilarProperties = (propertyId: string) => {
  const property = sampleProperties.find(p => p.id === propertyId)
  if (!property || !property.similarProperties) return []
  
  return property.similarProperties
    .map(id => sampleProperties.find(p => p.id === id))
    .filter(Boolean)
}